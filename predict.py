"""Web service that serves the purchase-prediction model.

Run locally:

    uv run uvicorn predict:app --host 0.0.0.0 --port 9696

Endpoints:

    GET  /health   -> liveness check and model information
    POST /predict  -> purchase probability for one browsing session
    GET  /docs     -> interactive API documentation (Swagger UI, generated by FastAPI)
"""

from __future__ import annotations

import os
import pickle
from pathlib import Path
from typing import Any, Literal

from fastapi import FastAPI
from pydantic import BaseModel, ConfigDict, Field

from features import prepare_record

MODEL_PATH = Path(os.getenv("MODEL_PATH", Path(__file__).with_name("model.bin")))

with MODEL_PATH.open("rb") as f_in:
    artifact = pickle.load(f_in)

pipeline = artifact["pipeline"]
THRESHOLD = float(artifact["threshold"])
METADATA: dict[str, Any] = artifact["metadata"]

EXAMPLE_SESSION = {
    "administrative": 3,
    "administrative_duration": 87.5,
    "informational": 0,
    "informational_duration": 0.0,
    "product_related": 34,
    "product_related_duration": 1280.4,
    "bounce_rates": 0.004,
    "exit_rates": 0.017,
    "page_values": 21.3,
    "special_day": 0.0,
    "month": "Nov",
    "operating_systems": 2,
    "browser": 2,
    "region": 1,
    "traffic_type": 2,
    "visitor_type": "Returning_Visitor",
    "weekend": False,
}


class Session(BaseModel):
    """One browsing session on the shop, described by the 17 features of the dataset."""

    model_config = ConfigDict(extra="forbid", json_schema_extra={"example": EXAMPLE_SESSION})

    administrative: int = Field(ge=0, description="Number of account-management pages visited")
    administrative_duration: float = Field(ge=0, description="Seconds spent on account-management pages")
    informational: int = Field(ge=0, description="Number of informational pages visited")
    informational_duration: float = Field(ge=0, description="Seconds spent on informational pages")
    product_related: int = Field(ge=0, description="Number of product-related pages visited")
    product_related_duration: float = Field(ge=0, description="Seconds spent on product-related pages")
    bounce_rates: float = Field(ge=0, le=1, description="Average Google Analytics bounce rate of the visited pages (0-1)")
    exit_rates: float = Field(ge=0, le=1, description="Average Google Analytics exit rate of the visited pages (0-1)")
    page_values: float = Field(ge=0, description="Average Google Analytics page value of the visited pages")
    special_day: float = Field(ge=0, le=1, description="Closeness of the visit to a special day such as Valentine's Day (0-1)")
    month: Literal["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"] = Field(
        description="Month of the visit (the training data has no sessions from Jan or Apr)"
    )
    operating_systems: int = Field(ge=1, description="Operating-system code (1-8 in the training data)")
    browser: int = Field(ge=1, description="Browser code (1-13 in the training data)")
    region: int = Field(ge=1, description="Region code (1-9 in the training data)")
    traffic_type: int = Field(ge=1, description="Traffic-source code (1-20 in the training data)")
    visitor_type: Literal["Returning_Visitor", "New_Visitor", "Other"] = Field(description="Type of visitor")
    weekend: bool = Field(description="Whether the visit happened on a weekend")


class Prediction(BaseModel):
    purchase_probability: float = Field(description="Predicted probability that the session ends with a purchase")
    purchase: bool = Field(description="True when the probability is at or above the decision threshold")
    threshold: float = Field(description="Decision threshold used for the `purchase` flag")


app = FastAPI(
    title="Online shopper purchase prediction",
    description="Predicts whether a browsing session on an online shop will end with a purchase.",
    version="1.0.0",
)


def predict_single(session: dict[str, Any]) -> tuple[float, bool]:
    """Return (purchase probability, decision) for one raw session dictionary."""
    record = prepare_record(session)
    probability = float(pipeline.predict_proba([record])[0, 1])
    return probability, probability >= THRESHOLD


@app.get("/health")
def health() -> dict[str, Any]:
    return {"status": "ok", "model": METADATA["model"], "threshold": THRESHOLD}


@app.post("/predict", response_model=Prediction)
def predict(session: Session) -> Prediction:
    probability, decision = predict_single(session.model_dump())
    return Prediction(
        purchase_probability=round(probability, 6),
        purchase=decision,
        threshold=THRESHOLD,
    )


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(app, host="0.0.0.0", port=9696)
